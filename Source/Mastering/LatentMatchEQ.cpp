void LatentMatchEQ::processBlock(juce::AudioBuffer<float>& buffer, juce::MidiBuffer&)
{
    if (!hasAnalyzedReference || matchAmount.load() < 0.01f)
        return;

    // Apply the FIR filter generated by the Neural Network
    juce::dsp::AudioBlock<float> block(buffer);
    juce::dsp::ProcessContextReplacing<float> context(block);
    
    // In a real scenario, we'd blend the dry and wet signal based on matchAmount
    convolutionFilter.process(context);
}
